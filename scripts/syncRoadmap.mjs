// Keeps README.md in step with ROADMAP-STATUS.md.
//
//   1. Tick a module in ROADMAP-STATUS.md (change its ➖ to ✅ in the API / screens columns and in "Overall").
//   2. Run:  node scripts/syncRoadmap.mjs
//
// It rewrites two things in README.md: the "Current build status" progress block (between the build-status markers)
// and the Status column of the "Implementation order" table. The counts in ROADMAP-STATUS.md's own summary table are
// not touched; update those by hand or ask Claude to.
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const statusPath = join(root, 'ROADMAP-STATUS.md')
const readmePath = join(root, 'README.md')

const status = readFileSync(statusPath, 'utf8')

// Part 1 of the tracker is the admin web table: | M07 | Name | API | Web UI | Overall | Notes |
const part1 = status.slice(status.indexOf('## Part 1'), status.indexOf('## Part 2'))
const part2 = status.slice(status.indexOf('## Part 2'), status.indexOf('## Suggested next steps'))
const rows = (section) =>
  [...section.matchAll(/^\| (M\d+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \| ([^|]+) \|/gm)].map((m) => ({ id: m[1], name: m[2].trim(), api: m[3].trim(), ui: m[4].trim(), overall: m[5].trim() }))

const admin = rows(part1)
const mobile = rows(part2)
if (admin.length !== 51) throw new Error(`Expected 51 admin modules in ROADMAP-STATUS.md, found ${admin.length}`)

const count = (list) => ({
  complete: list.filter((r) => r.overall === '✅').length,
  apiOnly: list.filter((r) => r.overall === '🟡' && r.api === '✅' && r.ui === '➖').length,
  partly: list.filter((r) => r.overall === '🟡' && !(r.api === '✅' && r.ui === '➖')).length,
  notStarted: list.filter((r) => r.overall === '➖').length,
})
const a = count(admin)
const m = count(mobile)
const total = admin.length + mobile.length
const done = a.complete + m.complete
const pct = Math.round((100 * done) / total)
const byId = new Map(admin.map((r) => [r.id, r]))
const list = (pick) => admin.filter(pick).map((r) => r.id).join(', ') || 'none'

const block = `<!-- build-status:start (generated by scripts/syncRoadmap.mjs from ROADMAP-STATUS.md; edit that file, not this block) -->
**Progress: ${a.complete} of ${admin.length} admin modules are complete** (${done} of ${total} counting the mobile app, about ${pct}%). The per-module tracker, with the API and the screens ticked separately for the admin portal and the mobile app, is in [ROADMAP-STATUS.md](ROADMAP-STATUS.md). The *Status* column of the table below is kept in step with it.

✅ done (API and screens, tests passing) · 🟡 partly done · ➖ not started

| | Complete | API only | Partly done | Not started |
| --- | --- | --- | --- | --- |
| **Admin web** (${admin.length}) | **${a.complete}** | ${a.apiOnly} | ${a.partly} | ${a.notStarted} |
| **Mobile app** (${mobile.length}) | **${m.complete}** | ${m.apiOnly} | ${m.partly} | ${m.notStarted} |

- **Admin modules complete:** ${list((r) => r.overall === '✅')}
- **Admin modules with an API but no screens yet:** ${list((r) => r.overall === '🟡')}
<!-- build-status:end -->`

let readme = readFileSync(readmePath, 'utf8')

const start = readme.indexOf('<!-- build-status:start')
const end = readme.indexOf('<!-- build-status:end -->')
if (start === -1 || end === -1) throw new Error('README.md is missing the build-status markers')
readme = readme.slice(0, start) + block + readme.slice(end + '<!-- build-status:end -->'.length)

// Implementation order table: add or refresh a Status column right after Module.
const lines = readme.split('\n')
const header = lines.findIndex((l) => /^\| # \| Module \|/.test(l))
if (header === -1) throw new Error('README.md has no Implementation order table')
const cells = (line) => line.slice(1, line.lastIndexOf('|')).split('|').map((c) => c.trim())
const rejoin = (parts) => `| ${parts.join(' | ')} |`

if (!cells(lines[header]).includes('Status')) {
  const h = cells(lines[header])
  h.splice(2, 0, 'Status')
  lines[header] = rejoin(h)
  const sep = cells(lines[header + 1])
  sep.splice(2, 0, '---')
  lines[header + 1] = rejoin(sep)
}
let ticked = 0
for (let i = header + 2; i < lines.length && lines[i].startsWith('| ['); i++) {
  const c = cells(lines[i])
  const statusIndex = cells(lines[header]).indexOf('Status')
  const id = /\[(M\d+)\]/.exec(c[0])?.[1]
  const row = id ? byId.get(id) : undefined
  if (!row) continue
  const hasStatus = c.length === cells(lines[header]).length
  if (hasStatus) c[statusIndex] = row.overall
  else c.splice(statusIndex, 0, row.overall)
  lines[i] = rejoin(c)
  ticked += 1
}
if (ticked !== admin.length) throw new Error(`Updated ${ticked} table rows but the tracker lists ${admin.length} modules`)

writeFileSync(readmePath, lines.join('\n'))
console.log(`README.md updated: ${a.complete}/${admin.length} admin modules complete, ${done}/${total} overall (${pct}%).`)
